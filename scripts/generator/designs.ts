import type { FuelPhase, GravityLevel, SafetyPillar } from "@/lib/schema";

/**
 * Investigation designs. Names, projects, platforms and hardware groupings
 * follow real PSI combustion investigations. Everything numeric that ends up in
 * the dataset (test conditions, outcomes, findings) is generated from these
 * designs by the physics model in ./physics.ts.
 */

export type RunKind =
  | "solid-spread"
  | "solid-pyrolysis"
  | "dust"
  | "gas-burner"
  | "gas-jet"
  | "gas-spherical"
  | "gas-coolflame"
  | "droplet"
  | "droplet-coolflame";

export type DiluentOption = { diluent: string | null; percents: readonly number[] };

export type InvestigationDesign = {
  id: string;
  name: string;
  acronym: string;
  project: string;
  platform: string;
  hardware: string[];
  yearsActive: { start: number; end: number };
  fuelPhase: FuelPhase;
  fuels: string[];
  sampleGeometry: string;
  gravityLevel: GravityLevel;
  objectives: string[];
  variables: string[];
  constants: string[];
  measurements: string[];
  safetyPillars: SafetyPillar[];
  earthApplications: string[];
  kind: RunKind;
  testCount: number;
  o2Levels: readonly number[];
  pressureLevels: readonly number[];
  /** null means quiescent (no imposed flow). */
  flowLevels: readonly number[] | null;
  diluentOptions: readonly DiluentOption[];
  sampleSizeMm: readonly [number, number];
  /** Fraction of runs flown as 1 g ground-reference tests. */
  groundReferenceFraction?: number;
  measuresTemperature: boolean;
  measuresSmoke: boolean;
  /** Test time limit, seconds. */
  maxBurnS: number;
  /** Per-fuel multiplier on flame spread (thin fabrics spread faster than thick plastics). */
  spreadFactor?: Readonly<Record<string, number>>;
  /** Per-material multiplier on smoke obscuration. */
  smokeFactor?: Readonly<Record<string, number>>;
};

